//! crates/mnemos-ui/src/font.rs
//!
//! Crisp bitmap typography engine with symbol rendering for Maccy shortcuts,
//! multiline return indicators, search glyphs, and pin marks.

use crate::draw::Surface;
use crate::geom::{Color, Rect};

#[derive(Clone, Copy, Debug)]
pub struct Font {
    pub char_width: i32,
    pub char_height: i32,
}

impl Font {
    pub const fn regular() -> Self {
        Font { char_width: 8, char_height: 14 }
    }

    pub const fn small() -> Self {
        Font { char_width: 6, char_height: 10 }
    }

    pub fn measure_str(&self, text: &str) -> Rect {
        let w = (text.chars().count() as i32) * self.char_width;
        Rect::new(0, 0, w, self.char_height)
    }
}

pub fn draw_text<S: Surface + ?Sized>(s: &mut S, x: i32, y: i32, text: &str, color: Color) {
    draw_text_font(s, x, y, text, color, &Font::regular());
}

pub fn draw_text_small<S: Surface + ?Sized>(s: &mut S, x: i32, y: i32, text: &str, color: Color) {
    draw_text_font(s, x, y, text, color, &Font::small());
}

pub fn draw_text_font<S: Surface + ?Sized>(
    s: &mut S,
    x: i32,
    y: i32,
    text: &str,
    color: Color,
    font: &Font,
) {
    let mut cx = x;
    for ch in text.chars() {
        if ch == '\n' {
            continue;
        }
        draw_char(s, cx, y, ch, color, font);
        cx += font.char_width;
    }
}

pub fn draw_char<S: Surface + ?Sized>(s: &mut S, x: i32, y: i32, ch: char, color: Color, font: &Font) {
    if ch == ' ' {
        return;
    }

    // Special procedural glyphs
    match ch {
        '↩' => {
            // Return / enter hooked arrow
            let aw = font.char_width.min(10);
            let ah = font.char_height.min(12);
            let mid_y = y + ah / 2;
            // horizontal line
            s.draw_line(x + 2, mid_y, x + aw - 2, mid_y, color);
            // vertical upward hook
            s.draw_line(x + aw - 2, mid_y - (ah / 3), x + aw - 2, mid_y, color);
            // arrow head
            s.draw_line(x + 2, mid_y, x + 5, mid_y - 3, color);
            s.draw_line(x + 2, mid_y, x + 5, mid_y + 3, color);
            return;
        }
        '■' => {
            // Color swatch square
            let size = (font.char_height * 2) / 3;
            let sy = y + (font.char_height - size) / 2;
            s.fill_rect(Rect::new(x + 1, sy, size, size), color);
            return;
        }
        '📌' => {
            // Pin marker
            let px = x + font.char_width / 2;
            let py = y + 2;
            s.fill_circle(px, py + 3, 3, color);
            s.draw_line(px, py + 6, px, py + font.char_height - 3, color);
            return;
        }
        _ => {}
    }

    let glyph = get_glyph_bitmap(ch);
    for row in 0..8 {
        let bits = glyph[row];
        for col in 0..8 {
            if (bits & (1 << (7 - col))) != 0 {
                let px = x + ((col as i32) * font.char_width) / 8;
                let py = y + ((row as i32) * font.char_height) / 8;
                s.put_pixel(px, py, color);
                if font.char_width >= 8 && font.char_height >= 14 {
                    s.put_pixel(px + 1, py, color);
                }
            }
        }
    }
}

